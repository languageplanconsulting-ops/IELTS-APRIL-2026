// Merge NOT GIVEN (default) or FALSE / NO (--false) contrast JSON, written per chunk, into
// src/readingNotGivenContrastData.ts or src/readingFalseContrastData.ts.
// Usage: node scripts/buildNotGivenContrasts.mjs [--false] <items.json> <out-1.json> [out-2.json ...]
// Each contrast is checked: q must be a verbatim substring of the question and p of the evidence.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const isFalse = process.argv.includes('--false')
const [itemsFile, ...outFiles] = process.argv.slice(2).filter((arg) => arg !== '--false')
const GAP_LIST = isFalse
  ? ['opposite', 'number', 'quantity', 'time', 'who-what', 'negation']
  : ['time', 'extra-detail', 'comparison', 'cause', 'number', 'opinion', 'different-topic']
const GAPS = new Set(GAP_LIST)
// Source questions that are broken (an instruction line, or cut off mid-sentence) — skip until the source is fixed.
// (Found Nov 2026; the statements end mid-sentence in server/userProvidedReadingPracticeCambridge13–16.mjs.)
const SKIP_KEY_PREFIXES = [
  'label the diagram',
  'coconuts found on the west coast of',
  'steam ships sometimes used the ocean route to travel between london',
  'the trocadero museums mayan sculpture attracted',
  'whaley has plans to go to africa to set up',
  'there are more geoglyphs in the shape of',
  'participants in the couples experiment were aware that they were taking part in a',
  'only experienced builders were employed to construct'
]

const items = new Map(JSON.parse(readFileSync(itemsFile, 'utf8')).map((item) => [item.key, item]))
const contrasts = {}
const problems = []
for (const file of outFiles) {
  for (const c of JSON.parse(readFileSync(file, 'utf8'))) {
    const item = items.get(c.key)
    if (!item) { problems.push(`${c.key}: unknown key`); continue }
    if (SKIP_KEY_PREFIXES.some((prefix) => c.key === prefix || (prefix === "label the diagram" && c.key.startsWith(prefix)))) {
      problems.push(`${c.key}: skipped (broken source question)`); continue
    }
    const pParts = String(c.p).split(' ... ')
    if (!item.prompt.includes(c.q)) { problems.push(`${c.key}: q not in question`); continue }
    if (!pParts.every((part) => item.evidence.includes(part))) { problems.push(`${c.key}: p not in evidence`); continue }
    if (!GAPS.has(c.gap)) { problems.push(`${c.key}: bad gap ${c.gap}`); continue }
    if (!c.qTh || !c.pTh || !c.why) { problems.push(`${c.key}: missing Thai`); continue }
    contrasts[c.key] = { q: c.q, qTh: c.qTh, p: c.p, pTh: c.pTh, gap: c.gap, why: c.why }
  }
}

const body = Object.entries(contrasts)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join('\n')
const typeName = isFalse ? 'ReadingFalseGap' : 'ReadingNotGivenGap'
const constName = isFalse ? 'READING_FALSE_CONTRAST_DATA' : 'READING_NOT_GIVEN_CONTRAST_DATA'
const out = `// AUTO-GENERATED by scripts/buildNotGivenContrasts.mjs${isFalse ? ' --false' : ''} — do not edit by hand.
// ${isFalse ? 'FALSE / NO' : 'NOT GIVEN'} reading questions → the question words (q) vs the passage words (p)
// ${isFalse ? 'that contradict them' : 'closest to them (the passage never supports q)'}, with simple Thai, a gap type and a one-line reason.
// Keyed by normalizeReadingNotGivenKey(question prompt) from readingParaphrase.ts.
export type ${typeName} =
${GAP_LIST.map((gap) => `  | '${gap}'`).join('\n')}

export const ${constName}: Record<
  string,
  { q: string; qTh: string; p: string; pTh: string; gap: ${typeName}; why: string }
> = {
${body}
}
`
writeFileSync(join(here, '..', 'src', isFalse ? 'readingFalseContrastData.ts' : 'readingNotGivenContrastData.ts'), out)
console.error(`wrote ${Object.keys(contrasts).length} contrasts`)
if (problems.length) console.error(problems.join('\n'))
